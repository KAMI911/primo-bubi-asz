#!/usr/bin/env python3
"""Makes the two commentator portraits (Korda Gyorgy, Klarika) from the photo gfx/korda_klari.jpg and writes src/faces.c:
48x48 one-bit bitmaps (1 = white, 0 = black; the monochrome look) and, for the colour model, one colour pair per 4x4 cell
(the colour of its dark pixels and of its light pixels, 12 pairs shared by both portraits, found by k-means) plus the
palette. Needs Pillow. Usage: gen_faces.py src/faces.c [preview.png]"""
import sys, random
from PIL import Image, ImageFilter, ImageOps

SRC = "gfx/korda_klari.jpg"
SIZE = 48
# square crops (left, top, right, bottom) around the two faces in the 500x500 photo
LEVELS = [(60, 185), (45, 200)]                                 # per portrait: black point, white point
CROPS = [(222, 12, 432, 222), (14, 62, 224, 272)]


def portrait(box, levels):
    im = Image.open(SRC).convert("L").crop(box)
    im = im.resize((SIZE * 4, SIZE * 4), Image.LANCZOS).filter(ImageFilter.UnsharpMask(radius=3, percent=150, threshold=0))
    im = im.resize((SIZE, SIZE), Image.LANCZOS)
    lo, hi = levels                                                # dark stays dark, the grey backdrop and the skin go white
    im = im.point(lambda v: max(0, min(255, (v - lo) * 255 // (hi - lo))))
    return im.convert("1")                                         # Floyd-Steinberg dithering


def pack(im):
    px = im.load()
    out = []
    for y in range(SIZE):
        for k in range(SIZE // 8):
            out.append(sum((1 if px[k * 8 + b, y] else 0) << (7 - b) for b in range(8)))
    return out


def rgb(box):
    return Image.open(SRC).convert("RGB").crop(box).resize((SIZE, SIZE), Image.LANCZOS)


def cell_pairs(bw, col):
    """per 4x4 cell: mean colour of the black pixels and of the white pixels (6 numbers)"""
    pb, pc = bw.load(), col.load()
    out = []
    for cy in range(SIZE // 4):
        for cx in range(SIZE // 4):
            sums = [[0, 0, 0, 0], [0, 0, 0, 0]]
            for y in range(cy * 4, cy * 4 + 4):
                for x in range(cx * 4, cx * 4 + 4):
                    k = 1 if pb[x, y] else 0
                    for i in range(3):
                        sums[k][i] += pc[x, y][i]
                    sums[k][3] += 1
            a = [v / max(1, sums[k][3]) for k in (0, 1) for v in sums[k][:3]]
            for k in (0, 1):                                       # an empty class takes the other one's colour
                if not sums[k][3]:
                    a[3 * k:3 * k + 3] = a[3 * (1 - k):3 * (1 - k) + 3]
            if a[0] + a[1] + a[2] > a[3] + a[4] + a[5]:            # keep "dark" darker than "light"
                a = a[3:] + a[:3]
            a[:3] = [v * 0.55 for v in a[:3]]                      # darker darks: the eyes and the mouth stay visible
            out.append(a)
    return out


def kmeans(vs, k, seed=7):
    rnd = random.Random(seed)
    cent = [vs[rnd.randrange(len(vs))]]
    while len(cent) < k:                                           # k-means++ start
        d = [min(sum((a - b) ** 2 for a, b in zip(v, c)) for c in cent) for v in vs]
        r, acc = rnd.random() * sum(d), 0
        for v, dv in zip(vs, d):
            acc += dv
            if acc >= r:
                cent.append(v); break
    for _ in range(40):
        groups = [[] for _ in cent]
        for v in vs:
            groups[min(range(len(cent)), key=lambda i: sum((a - b) ** 2 for a, b in zip(v, cent[i])))].append(v)
        cent = [[sum(x) / len(g) for x in zip(*g)] if g else c for g, c in zip(groups, cent)]
    return cent


def c332(r, g, b):
    return (round(r / 255 * 7) << 5) | (round(g / 255 * 7) << 2) | round(b / 255 * 3)


def main():
    ims = [portrait(b, lv) for b, lv in zip(CROPS, LEVELS)]
    pairs = [cell_pairs(im, rgb(b)) for im, b in zip(ims, CROPS)]
    cent = kmeans(pairs[0] + pairs[1], 12)
    quant = [(c332(*c[:3]), c332(*c[3:])) for c in cent]
    # palette words: byte n = colour of pixel 0 in nibble n, byte 16 + n = colour of pixel 1; nibbles 0..3 are the game's
    pal = [0x000C, 0x02E0, 0, 0, 0, 0, 0, 0, 0xFFFF, 0xFFFF, 0, 0, 0, 0, 0, 0]
    for i, (c0, c1) in enumerate(quant):
        n = i + 4
        pal[n // 2] |= c0 << (8 * (n & 1))
        pal[8 + n // 2] |= c1 << (8 * (n & 1))
    nibs = []
    for pr in pairs:
        ns = [min(range(12), key=lambda i: sum((a - b) ** 2 for a, b in zip(v, cent[i]))) + 4 for v in pr]
        nibs.append([ns[i] << 4 | ns[i + 1] for i in range(0, len(ns), 2)])
    with open(sys.argv[1], "w") as f:
        f.write("/* generated by tools/gen_faces.py from gfx/korda_klari.jpg - do not edit */\n#include <stdint.h>\n"
                "const uint8_t face_bits[2][%d] = {\n" % (SIZE * SIZE // 8))
        for im in ims:
            d = pack(im)
            f.write("    {\n")
            for i in range(0, len(d), 15):
                f.write("        " + ", ".join("0x%02X" % b for b in d[i:i + 15]) + ",\n")
            f.write("    },\n")
        f.write("};\n#ifndef TARGET_BW\n/* colour model: the palette of the game with the 12 portrait colour pairs, and a nibble per 4x4 cell */\n")
        f.write("const uint16_t palette_color[16] = {%s};\n" % ", ".join("0x%04X" % w for w in pal))
        f.write("const uint8_t face_nib[2][%d] = {\n" % len(nibs[0]))
        for nb in nibs:
            f.write("    {" + ", ".join("0x%02X" % b for b in nb) + "},\n")
        f.write("};\n#endif\n")
    if len(sys.argv) > 2:
        sc = 6
        pv = Image.new("RGB", (2 * (SIZE + 4) * 2, SIZE), (128, 128, 128))
        for i, im in enumerate(ims):
            pv.paste(im.convert("RGB"), (i * (SIZE + 4), 0))
            col = Image.new("RGB", (SIZE, SIZE))
            px = im.load()
            for cy in range(SIZE // 4):
                for cx in range(SIZE // 4):
                    n = nibs[i][(cy * (SIZE // 4) + cx) // 2]
                    n = (n >> 4) if (cy * (SIZE // 4) + cx) % 2 == 0 else n & 15
                    c0, c1 = quant[n - 4]
                    for y in range(cy * 4, cy * 4 + 4):
                        for x in range(cx * 4, cx * 4 + 4):
                            c = c1 if px[x, y] else c0
                            col.putpixel((x, y), (((c >> 5) & 7) * 255 // 7, ((c >> 2) & 7) * 255 // 7, (c & 3) * 255 // 3))
            pv.paste(col, ((2 + i) * (SIZE + 4), 0))
        pv.resize((pv.width * sc, pv.height * sc), Image.NEAREST).save(sys.argv[2])


main()
