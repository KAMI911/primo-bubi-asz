#!/usr/bin/env python3
"""Generates build/emu_script.h: a key script for the Z80 emulator run (tests/hw_ticks.c).
It plays both games with calls, folds, raises of every size and all in (with the question),
so the commentators, the confirmation and the deepest engine paths all run; the run reports the deepest stack use."""
import sys
SC = dict(UP=0x01, DOWN=0x0F, LEFT=0x39, RIGHT=0x3D, SPACE=0x19, RET=0x37, M=0x3F, T=0x16, C=0x10, F=0x12, R=0x14, Z=0x22, S=0x02)
ev, shots, f = [], [], 20
def tap(k, gap=14):
    global f
    ev.append((f, SC[k], 1)); ev.append((f + 4, SC[k], 0)); f += gap
def wait(n):
    global f; f += n
def shot(): shots.append(f); wait(6)

tap("SPACE", 30); shot()                       # title -> name entry
tap("Z", 16); tap("S", 16); shot()
tap("RET", 60); shot()                         # menu
row = 0
for g in range(2):                             # 0 Texas Hold'em (the default), 1 Omaha
    while row < g: tap("DOWN", 16); row += 1
    tap("SPACE", 40); wait(40); shot()         # a new session of game g
    for hand in range(8):
        for rnd in range(4):                   # a hand: several decisions, next-hand prompts
            if hand % 5 == 1: tap("F", 12)
            elif hand % 5 == 2:                # a raise of some size, then all in with the question
                for _ in range(rnd + 1): tap("UP", 8)
                tap("R", 12); tap("C", 12)
            elif hand % 5 == 3: tap("T", 12); tap("SPACE", 12); tap("DOWN", 12)
            else: tap("C", 12)
            tap("C", 12)
        tap("SPACE", 20)
    wait(10); shot()
    tap("M", 20); tap("M", 40); wait(300); tap("M", 20); tap("M", 40)   # leave the table (the hand is played out first)
end = f + 400
ev.sort()
assert len(ev) <= 2000, len(ev)
blob = bytearray(); prev = 0
for fr, sc, down in ev:
    d = fr - prev
    while d > 255:                                   # a long gap: a harmless extra event (key 63 released)
        blob += bytes([255, 63]); d -= 255
    blob += bytes([d, sc | (0x80 if down else 0)]); prev = fr
nev = len(blob) // 2
with open(sys.argv[1], "w") as o:
    o.write("/* generated by tools/gen_emu_script.py */\n#include <stdint.h>\n")
    o.write("#define SCRIPT_LEN %d\nstatic const uint16_t shots[] = {%s};\n#define SHOT_COUNT %d\n#define END_FRAME %d\n"
            % (nev, ", ".join(map(str, shots)), len(shots), end))
open(sys.argv[1].replace(".h", ".bin"), "wb").write(blob)
