#!/usr/bin/env python3
"""Gyorgy's and Klarika's comments: src/chat.txt -> a C header with the compressed text of one language.
The texts are squeezed with byte-pair coding: the 128 most useful letter pairs get the codes 128..255 (a pair table of two
bytes each; a pair may contain pairs), the strings sit one after the other, each ended by 0. Play.c unpacks one string at a time
into a buffer (chat_text). Accented capitals become the font codes 0x60..0x68 like in tools/accents.py.
Usage: gen_chat.py src/chat.txt en|hu out.h"""
import sys
import collections

CATS = ["ALLIN", "BUBIASZ", "FOLD", "AIWIN", "MEWIN", "BROKE", "IDLE", "SHOW", "RIVER", "ALLINC", "TURN", "BLUFF", "NICE"]
ACC = "ÁÉÍÓÖŐÚÜŰ"
RR, NONE = 0xFE, 0xFF

src, lang, dst = sys.argv[1], sys.argv[2], sys.argv[3]
col = 1 if lang == "en" else 2
strings, quips, replies, asks = [], [], [], []
named_replies = 0                              # the replies that use the player's name must be the last ones of the R block
rules = [[] for _ in range(3)]                 # string numbers of the rules page lines: the games (hold'em, omaha), then the common part


def add(s):
    s = s.strip()
    for i, ch in enumerate(ACC):
        s = s.replace(ch, chr(0x60 + i))
    if not s or any(ord(c) > 104 or ord(c) < 32 for c in s):
        sys.exit("gen_chat: bad text %r" % s)
    strings.append(s)
    return len(strings) - 1


for ln in open(src, encoding="utf-8").read().split("\n"):
    if not ln.strip() or ln.startswith("#"):
        continue
    f = [x.strip() for x in ln.split("|")]
    head = f[0].split()
    k = head[0]
    if k in "GKD":
        cat = CATS.index(head[1])
        t = add(f[col])
        re_ = add(f[2 + col]) if len(f) > 3 else (RR if k == "D" else NONE)
        named = "%" in f[col] or (len(f) > 3 and "%" in f[2 + col])               # speaks to the player by name: not said after the player folded
        quips.append((cat | (16 if k == "K" else 0) | (32 if named else 0), t, re_))
    elif k == "L":
        rules["C" == head[1] and 2 or int(head[1])].append(add(f[col]))
    elif k in "RA":
        (replies if k == "R" else asks).append(add(f[col]))
        if k == "R" and "%" in f[col]: named_replies += 1
    else:
        sys.exit("gen_chat: bad line " + ln)
# replies and asks are consecutive in the string list only by construction: the strings are added in file order, R lines then A lines
assert replies == list(range(replies[0], replies[0] + len(replies))) and asks == list(range(asks[0], asks[0] + len(asks)))

for r in rules:
    assert r and r == list(range(r[0], r[0] + len(r))), "rules lines of a group must be consecutive"
seqs = [[ord(c) for c in s] for s in strings]
pairs = []
while len(pairs) < 128:
    cnt = collections.Counter()
    for s in seqs:
        for a, b in zip(s, s[1:]):
            cnt[(a, b)] += 1
    if not cnt:
        break
    p, n = max(cnt.items(), key=lambda kv: (kv[1], kv[0]))
    if n < 3:
        break
    code = 128 + len(pairs)
    pairs.append(p)
    for i, s in enumerate(seqs):
        o, j = [], 0
        while j < len(s):
            if j + 1 < len(s) and (s[j], s[j + 1]) == p:
                o.append(code); j += 2
            else:
                o.append(s[j]); j += 1
        seqs[i] = o


blob = []
for s in seqs:
    blob += [x for x in s] + [0]
out = ["/* generated by tools/gen_chat.py from src/chat.txt (%s) - do not edit */" % lang,
       "enum { %s };" % ", ".join("Q_%s%s" % (c, " = 0" if i == 0 else "") for i, c in enumerate(CATS)),
       "#define CH_NQUIPS %d" % len(quips), "#define CH_REPLY0 %d" % replies[0], "#define CH_NREPLY %d" % len(replies),
       "#define CH_NPLAIN %d" % (len(replies) - named_replies), "#define CH_ASK0 %d" % asks[0], "#define CH_NASK %d" % len(asks), "#define CH_RR %d" % RR,
       "static const uint8_t ch_rules[3][2] = {%s};   /* first string, number of lines: the two games, the common part */" % ", ".join("{%d,%d}" % (r[0], len(r)) for r in rules),
       "#define CH_MAXLEN %d" % max(len(s) for s in strings),
       "static const uint8_t ch_pair[%d][2] = {%s};" % (len(pairs), ", ".join("{%d,%d}" % (a, b) for a, b in pairs)),
       "static const uint8_t ch_quip[CH_NQUIPS][3] = {%s};   /* category | 16 if Klarika, text, her answer (CH_RR: a random reply, 255: none) */" % ", ".join("{%d,%d,%d}" % q for q in quips),
       "static const uint8_t ch_blob[%d] = {" % len(blob)]
for i in range(0, len(blob), 24):
    out.append("  " + ",".join(map(str, blob[i:i + 24])) + ",")
out.append("};")
open(dst, "w").write("\n".join(out) + "\n")
print("%s: %d strings, %d characters -> %d bytes + %d pair table, longest %d" % (lang, len(strings), sum(map(len, strings)) + len(strings), len(blob), 2 * len(pairs), max(len(s) for s in strings)))
